#!/usr/bin/env python3
"""Regenerate mods/draftwatch-diff/engine.py from a Draftwatch checkout.

The word diff, the change ids and the revert reconstruction must be exactly
Draftwatch's. Rather than rewrite them, this copies the functions verbatim out
of Draftwatch's `draftwatch/app.py` at a committed revision and records which
one. Never edit engine.py by hand: change Draftwatch, then run this.

    python3 tools/sync_engine.py /path/to/Draftwatch [git-revision]
    python3 tools/sync_engine.py /path/to/Draftwatch --check   # exit 1 if stale
"""
import ast
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "mods", "draftwatch-diff", "engine.py")

# In dependency order. Everything these need is the standard library.
FUNCTIONS = [
    "run_git", "git_toplevel", "is_tracked", "commit_list", "push_ref",
    "verify_commit_ref", "git_diff_text", "parse_word_diff",
    "_assign_content_ids", "_decide", "reconstruct", "read_text",
    "write_file", "file_mtime",
]

HEADER = '''"""Draftwatch's diff engine, copied verbatim. DO NOT EDIT.

Generated by tools/sync_engine.py from Draftwatch (MIT, Mike Konczal)
  https://github.com/mtkonczal/Draftwatch
  draftwatch/app.py at commit {commit}

These are the functions the Draftwatch app itself uses to run the git word
diff, give each change a stable id, and rebuild the file when a change is
reverted. They are copied, not rewritten, so the Herdr panes and the app
agree on every word.
"""
import hashlib
import os
import subprocess
import time
'''


def build(repo, rev):
    commit = subprocess.run(["git", "rev-parse", rev], cwd=repo, check=True,
                            capture_output=True, text=True).stdout.strip()
    source = subprocess.run(["git", "show", commit + ":draftwatch/app.py"], cwd=repo, check=True,
                            capture_output=True, text=True).stdout
    found = {n.name: ast.get_source_segment(source, n)
             for n in ast.parse(source).body if isinstance(n, ast.FunctionDef)}
    missing = [f for f in FUNCTIONS if f not in found]
    if missing:
        sys.exit("Draftwatch no longer has: " + ", ".join(missing))
    return HEADER.format(commit=commit) + "".join("\n\n" + found[f] + "\n" for f in FUNCTIONS)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if not args:
        sys.exit(__doc__)
    text = build(args[0], args[1] if len(args) > 1 else "HEAD")
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if current != text:
            sys.exit("engine.py is out of date with %s" % args[0])
        print("engine.py matches")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d lines)" % (OUT, text.count("\n")))


if __name__ == "__main__":
    main()
